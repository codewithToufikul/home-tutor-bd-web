/**
 * Returns the appropriate university list based on institute type.
 */
export function getUniversityOptions(instituteType: string): string[] {
  if (instituteType === 'Public University') return publicUniversities;
  if (instituteType === 'Private University') return privateUniversities;
  if (instituteType === 'Medical College') return medicalColleges;
  if (instituteType === 'National University') return nationalUniversityColleges;
  // Engineering / BUET, Other — free text entry, no preset list
  return [];
}

